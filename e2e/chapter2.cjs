const { chromium } = require('playwright');

const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('ok -', m); };
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 760 }, colorScheme: 'dark' })).newPage();
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.text()); });
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  const counter = async () => (await page.locator('.lesson__count').innerText()).trim();
  await page.goto('' + (process.env.BASE_URL || 'http://127.0.0.1:5173') + '/login');
  await page.getByRole('button', { name: /sinov rejimida/i }).click();
  await page.goto('' + (process.env.BASE_URL || 'http://127.0.0.1:5173') + '/learn/ch2-files');
  await page.waitForSelector('.sim-stage');
  await page.getByRole('button', { name: 'Davom etish' }).click();
  await page.locator('.sim-icon', { hasText: 'Hujjatlar' }).click();
  await page.locator('.sim-icon', { hasText: 'Hujjatlar' }).dblclick();
  assert((await counter()) === '3 / 18', 'documents opened');
  await page.getByRole('button', { name: 'Yangi papka' }).click();
  assert((await counter()) === '4 / 18', 'new folder created, rename editing');
  // wrong name
  await page.locator('.sim-rename__input').fill('Boshqa');
  await page.keyboard.press('Enter');
  await page.waitForSelector('.note--wrong');
  assert((await counter()) === '4 / 18', 'wrong name does not advance');
  await page.screenshot({ path: (process.env.OUT || '/tmp') + '/20-wrong-name.png' });
  // fallback target: rename button highlighted; recover
  await page.locator('.sim-item', { hasText: 'Boshqa' }).click();
  await page.getByRole('button', { name: 'Nomini o‘zgartirish' }).click();
  await page.locator('.sim-rename__input').fill('Loyiha');
  await page.keyboard.press('Enter');
  assert((await counter()) === '5 / 18', 'correct name advances');
  await page.locator('.sim-item', { hasText: 'Loyiha' }).click();
  await page.locator('.sim-item', { hasText: 'Loyiha' }).dblclick().catch(()=>{});
  assert((await counter()) === '6 / 18', 'entered Loyiha');
  await page.getByRole('button', { name: 'Yuqoriga' }).click();
  assert((await counter()) === '7 / 18', 'went up');
  await page.locator('.sim-item', { hasText: 'Hisobot.txt' }).click();
  assert((await counter()) === '8 / 18', 'selected file');
  await page.getByRole('button', { name: 'Nusxalash' }).click();
  assert((await counter()) === '9 / 18', 'copied');
  await page.locator('.sim-item', { hasText: 'Loyiha' }).click();
  await page.locator('.sim-item', { hasText: 'Loyiha' }).dblclick().catch(()=>{});
  assert((await counter()) === '10 / 18', 'entered destination');
  await page.screenshot({ path: (process.env.OUT || '/tmp') + '/21-before-paste.png' });
  await page.getByRole('button', { name: 'Qo‘yish' }).click();
  assert((await page.locator('.sim-item', { hasText: 'Hisobot.txt' }).count()) === 1, 'pasted file really exists in Loyiha');
  assert((await counter()) === '11 / 18', 'paste advanced');
  await page.getByRole('button', { name: 'Nomini o‘zgartirish' }).click();
  await page.locator('.sim-rename__input').fill('Hisobot-2026.txt');
  await page.keyboard.press('Enter');
  assert((await counter()) === '13 / 18', 'renamed');
  await page.getByRole('button', { name: 'O‘chirish' }).click();
  assert((await counter()) === '14 / 18', 'deleted to trash');
  assert((await page.locator('.sim-item').count()) === 0, 'file gone from folder');
  await page.locator('.sim-nav').getByRole('button', { name: 'Savat' }).click();
  assert((await counter()) === '15 / 18', 'trash opened');
  await page.locator('.sim-item', { hasText: 'Hisobot-2026.txt' }).click();
  assert((await counter()) === '16 / 18', 'selected in trash');
  await page.getByRole('button', { name: 'Tiklash' }).click();
  assert((await counter()) === '17 / 18', 'restored');
  await page.getByPlaceholder('Qidirish…').fill('hisobot');
  assert((await counter()) === '18 / 18', 'search advanced');
  await page.screenshot({ path: (process.env.OUT || '/tmp') + '/22-search.png' });
  await page.getByRole('button', { name: 'Davom etish' }).click();
  await page.waitForSelector('text=Bob yakunlandi');
  console.log('console problems:', errors);
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
