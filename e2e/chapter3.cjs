const { chromium } = require('playwright');
const BASE = process.env.BASE_URL || 'http://127.0.0.1:5173';
const OUT = process.env.OUT || '/tmp';
const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('ok -', m); };
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 760 }, colorScheme: 'dark' })).newPage();
  const errors = [];
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.text()); });
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  const counter = async () => (await page.locator('.lesson__count').innerText()).trim();
  const ta = page.locator('.sim-notepad__text');
  await page.goto(BASE + '/login');
  await page.getByRole('button', { name: /sinov rejimida/i }).click();
  await page.goto(BASE + '/learn/ch3-keyboard');
  await page.waitForSelector('.sim-stage');
  await page.getByRole('button', { name: 'Davom etish' }).click();
  await page.locator('.sim-icon', { hasText: 'Bloknot' }).dblclick();
  assert((await counter()) === '3 / 18', 'notepad opened');
  await ta.click(); await page.keyboard.type('Salom, dunyo!');
  assert((await counter()) === '4 / 18', 'typed with real keyboard');
  await page.keyboard.press('Control+a');
  assert((await counter()) === '5 / 18', 'Ctrl+A');
  await page.keyboard.press('Control+c');
  assert((await counter()) === '6 / 18', 'Ctrl+C');
  await page.keyboard.press('Control+v'); // replaces selection -> must not advance
  assert((await counter()) === '6 / 18', 'paste over selection does not advance');
  await page.screenshot({ path: OUT + '/30-ch3-paste-wrong.png' });
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('Control+v');
  assert((await ta.inputValue()) === 'Salom, dunyo!Salom, dunyo!', 'text doubled');
  assert((await counter()) === '7 / 18', 'Ctrl+V after caret move');
  await page.keyboard.press('Control+z');
  assert((await ta.inputValue()) === 'Salom, dunyo!', 'Ctrl+Z restored');
  assert((await counter()) === '8 / 18', 'undo advanced');
  await page.keyboard.press('Control+a'); await page.keyboard.press('Control+x');
  assert((await ta.inputValue()) === '', 'Ctrl+X emptied');
  assert((await counter()) === '9 / 18', 'cut advanced');
  await page.keyboard.press('Control+v');
  assert((await ta.inputValue()) === 'Salom, dunyo!', 'pasted back');
  assert((await counter()) === '10 / 18', 'paste-back advanced');
  await page.keyboard.press('Control+s');
  await page.waitForSelector('.sim-saveform');
  await page.locator('.sim-saveform input').fill('Eslatma-2.txt');
  await page.keyboard.press('Enter');
  assert((await counter()) === '11 / 18', 'Ctrl+S saved');
  await page.locator('.sim-win', { hasText: 'Bloknot' }).getByRole('button', { name: 'Yopish' }).click();
  assert((await counter()) === '12 / 18', 'notepad closed');
  await page.locator('.sim-icon', { hasText: 'Hujjatlar' }).dblclick();
  assert((await counter()) === '13 / 18', 'documents opened');
  await page.locator('.sim-item', { hasText: 'Eslatma.txt' }).click();
  assert((await counter()) === '14 / 18', 'file selected');
  await page.keyboard.press('Control+c');
  assert((await counter()) === '15 / 18', 'Ctrl+C on file');
  await page.locator('.sim-nav').getByRole('button', { name: /Yuklamalar/ }).click();
  assert((await counter()) === '16 / 18', 'Downloads');
  await page.keyboard.press('Control+v');
  assert((await page.locator('.sim-item', { hasText: 'Eslatma.txt' }).count()) >= 1, 'pasted file visible');
  assert((await counter()) === '17 / 18', 'Ctrl+V on files');
  await page.keyboard.press('Delete');
  assert((await counter()) === '18 / 18', 'Delete key');
  await page.screenshot({ path: OUT + '/31-ch3-finish.png' });
  await page.getByRole('button', { name: /Tugatish|Yakunlash|Davom/ }).last().click().catch(() => {});
  const bad = errors.filter((e) => !/favicon|DevTools/.test(e));
  assert(bad.length === 0, 'no console errors ' + JSON.stringify(bad));
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
